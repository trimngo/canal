import {mkdir,copyFile,readFile,writeFile,cp} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('..',import.meta.url)));
await mkdir('dist/server',{recursive:true});
await mkdir('dist/.openai',{recursive:true});
const page=await readFile('checkins/index.html','utf8'),assets={};
for(const file of ['app.mjs','timeline.mjs','google.mjs','config.mjs','categories.mjs'])assets['/today/'+file]=await readFile('web/'+file,'utf8');
for(const file of ['app.mjs','core.mjs'])assets['/checkins/'+file]=await readFile('checkins/'+file,'utf8');
const serviceWorker=await readFile('checkins/sw.js','utf8');
const embedded='export const page='+JSON.stringify(page)+';\nexport const assets='+JSON.stringify(assets)+';\nexport const serviceWorker='+JSON.stringify(serviceWorker)+';\n';
await writeFile('worker/today-assets.mjs',embedded);
const entry=await readFile('worker/index.js','utf8');
const core=(await readFile('checkins/core.mjs','utf8')).replace(/^export /gm,'');
const backend=(await readFile('worker/checkins.mjs','utf8')).replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
await writeFile('dist/server/index.js',entry.replace("import {page as todayPage,assets as todayAssets,serviceWorker as checkinSw} from './today-assets.mjs';",'const todayPage='+JSON.stringify(page)+';\nconst todayAssets='+JSON.stringify(assets)+';\nconst checkinSw='+JSON.stringify(serviceWorker)+';').replace("import {handleCheckins,tickCheckins} from './checkins.mjs';",core+'\n'+backend));
await copyFile('.openai/hosting.json','dist/.openai/hosting.json');
await cp('drizzle','dist/.openai/drizzle',{recursive:true});
const manifest=JSON.parse(await readFile('dist/.openai/hosting.json','utf8'));
assert.equal(manifest.project_id,'appgprj_6acd1578782c81919c201533c55d02b9');
assert.ok(!manifest.static);
const source=await readFile('dist/server/index.js','utf8');
const module=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(typeof module.default.fetch,'function');
console.log('Worker built and validated.');
